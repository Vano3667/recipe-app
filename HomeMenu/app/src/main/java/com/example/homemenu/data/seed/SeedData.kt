    /** "Говядина (мякоть):800:g; ..." → ingredients. Names may contain '(', so split on ':' from the right. */
    private fun ing(spec: String): List<SeedIngredient> = spec.split(";").map { it.trim() }.filter { it.isNotEmpty() }.map { part ->
        val unit = part.substringAfterLast(':')
        val rest = part.substringBeforeLast(':')
        val amount = rest.substringAfterLast(':').toDouble()
        SeedIngredient(rest.substringBeforeLast(':').trim(), amount, unit.trim())
    }

